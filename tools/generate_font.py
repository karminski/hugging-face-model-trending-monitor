#!/usr/bin/env python3
"""Generate compact 1-bit ASCII bitmap fonts for the ESP32 firmware."""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


FIRST_CODEPOINT = 0x20
LAST_CODEPOINT = 0x7E


@dataclass(frozen=True)
class Glyph:
    bitmap_offset: int
    width: int
    height: int
    x_offset: int
    y_offset: int
    advance: int


def pack_bitmap(image: Image.Image, threshold: int) -> bytes:
    """Pack a grayscale image as row-major XBM data (least-significant bit first)."""
    width, height = image.size
    row_bytes = (width + 7) // 8
    packed = bytearray(row_bytes * height)
    pixels = image.load()

    for y in range(height):
        for x in range(width):
            if pixels[x, y] >= threshold:
                packed[y * row_bytes + x // 8] |= 1 << (x % 8)

    return bytes(packed)


def rasterize_font(
    font_path: Path, size: int, threshold: int
) -> tuple[bytes, list[Glyph], int, int, int]:
    font = ImageFont.truetype(str(font_path), size)
    ascent, descent = font.getmetrics()
    bitmap = bytearray()
    glyphs: list[Glyph] = []

    for codepoint in range(FIRST_CODEPOINT, LAST_CODEPOINT + 1):
        character = chr(codepoint)
        left, top, right, bottom = font.getbbox(character, anchor="ls")
        width = max(0, right - left)
        height = max(0, bottom - top)
        advance = round(font.getlength(character))
        offset = len(bitmap)

        if width > 0 and height > 0:
            image = Image.new("L", (width, height), 0)
            draw = ImageDraw.Draw(image)
            draw.text((-left, -top), character, font=font, fill=255, anchor="ls")
            bitmap.extend(pack_bitmap(image, threshold))

        glyphs.append(
            Glyph(
                bitmap_offset=offset,
                width=width,
                height=height,
                x_offset=left,
                y_offset=top,
                advance=advance,
            )
        )

    return bytes(bitmap), glyphs, ascent + descent, ascent, descent


def format_bytes(data: bytes, indent: str = "    ", per_line: int = 12) -> str:
    if not data:
        return f"{indent}0x00"

    lines = []
    for index in range(0, len(data), per_line):
        chunk = data[index : index + per_line]
        lines.append(indent + ", ".join(f"0x{value:02X}" for value in chunk))
    return ",\n".join(lines)


def font_identifier(size: int) -> str:
    return f"SarasaFixedSc{size}"


def render_font_definition(
    font_path: Path, size: int, threshold: int
) -> tuple[str, int]:
    bitmap, glyphs, line_height, ascent, descent = rasterize_font(
        font_path, size, threshold
    )
    identifier = font_identifier(size)
    glyph_lines = []

    for codepoint, glyph in zip(
        range(FIRST_CODEPOINT, LAST_CODEPOINT + 1), glyphs
    ):
        printable = chr(codepoint)
        label = printable if printable not in {"\\", "'"} else f"0x{codepoint:02X}"
        glyph_lines.append(
            "    "
            f"{{{glyph.bitmap_offset}, {glyph.width}, {glyph.height}, "
            f"{glyph.x_offset}, {glyph.y_offset}, {glyph.advance}}},"
            f" // {label}"
        )

    definition = f"""\
const uint8_t {identifier}Bitmaps[] PROGMEM = {{
{format_bytes(bitmap)}
}};

const BitmapGlyph {identifier}Glyphs[] PROGMEM = {{
{chr(10).join(glyph_lines)}
}};

const BitmapFont {identifier} = {{
    {identifier}Bitmaps,
    {identifier}Glyphs,
    0x{FIRST_CODEPOINT:02X},
    0x{LAST_CODEPOINT:02X},
    {line_height},
    {ascent},
    {descent}
}};
"""
    return definition, len(bitmap)


def generate_header(
    font_path: Path,
    output_path: Path,
    sizes: list[int],
    threshold: int,
) -> None:
    definitions = []
    total_bytes = 0

    for size in sizes:
        definition, bitmap_bytes = render_font_definition(
            font_path, size, threshold
        )
        definitions.append(definition)
        total_bytes += bitmap_bytes

    source = f"""\
// Generated by tools/generate_font.py. Do not edit manually.
// Source font: {font_path.name}
// Characters: ASCII 0x{FIRST_CODEPOINT:02X}-0x{LAST_CODEPOINT:02X}
// Threshold: {threshold}

#pragma once

#include "BitmapFont.h"

{chr(10).join(definitions)}
"""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(source, encoding="utf-8", newline="\n")
    print(
        f"Generated {output_path} with {len(sizes)} fonts, "
        f"{LAST_CODEPOINT - FIRST_CODEPOINT + 1} glyphs each, "
        f"{total_bytes} bitmap bytes."
    )


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", required=True, type=Path, help="Source TTF path")
    parser.add_argument("--output", required=True, type=Path, help="Output header")
    parser.add_argument(
        "--sizes",
        nargs="+",
        type=int,
        default=[20, 40],
        help="Pixel sizes to generate",
    )
    parser.add_argument(
        "--threshold",
        type=int,
        default=128,
        help="1-bit conversion threshold (0-255)",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    font_path = args.font.resolve()
    output_path = args.output.resolve()

    if not font_path.is_file():
        raise FileNotFoundError(f"Font not found: {font_path}")
    if not args.sizes or any(size <= 0 or size > 127 for size in args.sizes):
        raise ValueError("Font sizes must be between 1 and 127 pixels")
    if not 0 <= args.threshold <= 255:
        raise ValueError("Threshold must be between 0 and 255")

    generate_header(font_path, output_path, args.sizes, args.threshold)


if __name__ == "__main__":
    main()
